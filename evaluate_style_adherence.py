"""
Style Adherence Evaluation for IndicParler-TTS Long-Form Expression

Computes L_sem (semantic alignment) and L_dyn (dynamic style smoothness)
metrics from the proposal for evaluating style adherence in generated speech.

Usage:
    python evaluate_style_adherence.py

Requirements:
    - style_captions.json (generated by generate_captions.py)
    - IndicParler-TTS model loaded
    - StoricoTTSDataset/test.csv
"""

