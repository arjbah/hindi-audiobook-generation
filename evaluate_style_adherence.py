def load_test_segments():
    """Load test.csv segments with metadata."""
    segments = []
    with open(TEST_CSV, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            segments.append({
                'segment_id': os.path.basename(row['audio_filepath']).replace('.wav', ''),
                'audio_filepath': row['audio_filepath'],
                'character': row.get('character', '').strip(),
                'emotion': row.get('emotion', '').strip(),
                'text': row.get('text', ''),
                'story': row.get('story', ''),
            })
    return segments


def load_style_captions():
    """Load GPT-4o generated style captions."""
    with open(CAPTIONS_FILE, 'r', encoding='utf-8') as f:
        return json.load(f)


def get_style_caption_for_segment(segment_id, style_captions, segment):
    """
    Get style caption for a segment, with fallbacks for missing/failed captions.
    
    Priority:
    1. Use GPT-4o generated caption (if successful)
    2. Use existing emotion annotation (if available)
    3. Use character/narrator template
    4. Use default fallback
    """
    # Check if we have a generated caption
    caption_data = style_captions.get(segment_id, {})
    style_caption = caption_data.get('style_caption', '')
    
    # Check if caption failed
    if not style_caption or style_caption.startswith('[ERROR]'):
        # Fallback 1: Use existing emotion annotation
        if segment.get('emotion'):
            emotion = segment['emotion']
            # Convert Hindi emotion to English caption
            return f"spoken with emotion: {emotion}"
        
        # Fallback 2: Character vs narrator template
        if segment.get('character'):
            return "spoken expressively, character dialogue"
        else:
            return "spoken calmly, neutral narrator style"
    
    # Check if it's an [EXISTING] annotation
    if style_caption.startswith('[EXISTING]'):
        emotion = style_caption.replace('[EXISTING]', '').strip()
        return f"spoken with emotion: {emotion}"
    
    return style_caption


def group_segments_by_story(segments):
    """Group segments by story for L_dyn computation."""
    stories = {}
    for seg in segments:
        story_id = seg['story']
        if story_id not in stories:
            stories[story_id] = []
        stories[story_id].append(seg)
    
    # Sort each story by segment index
    for story_id in stories:
        stories[story_id].sort(
            key=lambda x: int(x['segment_id'].split('_')[-1])
        )
    
    return stories


