# ============================================================================

MODEL_NAME = "ai4bharat/indic-parler-tts"
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
CLAP_DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

DATA_DIR = "StoricoTTSDataset"
CLIPS_DIR = os.path.join(DATA_DIR, "clips")
CAPTIONS_FILE = os.path.join(DATA_DIR, "style_captions.json")
TEST_CSV = os.path.join(DATA_DIR, "test.csv")
OUTPUT_DIR = "evaluation_output"
GENERATED_AUDIO_DIR = os.path.join(OUTPUT_DIR, "generated")

# Create output directories
os.makedirs(GENERATED_AUDIO_DIR, exist_ok=True)

# Set to True for quick test with 1 story (5 segments)
# Set to False for full evaluation on all test segments
QUICK_TEST = False
QUICK_TEST_STORY = "23"
QUICK_TEST_LIMIT = 5

