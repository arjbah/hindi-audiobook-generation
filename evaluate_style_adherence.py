def generate_speech(model, tokenizer, description_tokenizer, device,
                    text, style_caption, output_path):
    """Generate speech using IndicParler-TTS."""

    # Clean up style caption (remove [EXISTING] prefix if present)
    if style_caption.startswith('[EXISTING]'):
        style_caption = style_caption.replace('[EXISTING]', '').strip()
    elif style_caption.startswith('[ERROR]'):
        style_caption = "neutral narration, clear speech"

    # Tokenize with proper tokenizers
    # description_tokenizer (T5) for English style captions
    # tokenizer (main) for Hindi transcript
    description_input_ids = description_tokenizer(
        style_caption, return_tensors="pt"
    ).to(device)
    prompt_input_ids = tokenizer(text, return_tensors="pt").to(device)

    # Generate
    with torch.no_grad():
        generation = model.generate(
            input_ids=description_input_ids.input_ids,
            attention_mask=description_input_ids.attention_mask,
            prompt_input_ids=prompt_input_ids.input_ids,
            prompt_attention_mask=prompt_input_ids.attention_mask,
        )

    # Convert to audio array
    audio_arr = generation.cpu().numpy().squeeze()
    
    # Validate audio array
    if audio_arr.ndim == 0 or audio_arr.size == 0:
        raise ValueError(f"Generated audio is empty or invalid. Shape: {audio_arr.shape}")
    
    # Ensure 1D array for mono audio
    if audio_arr.ndim > 1:
        audio_arr = audio_arr.mean(axis=0)  # Convert to mono if multi-channel

    # Save
    sf.write(output_path, audio_arr, model.config.sampling_rate)
    return output_path


# ============================================================================
# Embedding Extraction
# ============================================================================


def extract_style_embedding(model, device, audio_path):
    """
    Extract style embedding from generated audio using CLAP.
    CLAP provides joint text-audio embeddings in the same space.
    """
    # Load audio
    audio_arr, sr = sf.read(audio_path)

    # Resample to 48kHz for CLAP
    if sr != 48000:
        audio_arr = librosa.resample(audio_arr, orig_sr=sr, target_sr=48000)

    return audio_arr  # Return raw audio for CLAP processing


def extract_caption_embedding(model, description_tokenizer, device, style_caption):
    """
    Extract style embedding from text caption.
    Returns the caption text for CLAP processing.
    """
    # Clean caption
    if style_caption.startswith('[EXISTING]'):
        style_caption = style_caption.replace('[EXISTING]', '').strip()
    elif style_caption.startswith('[ERROR]'):
        style_caption = "neutral narration"

    return style_caption  # Return text for CLAP processing


def compute_l_sem_clap(clap_model, clap_processor, device, caption_text, audio_arr):
    """
    Compute L_sem using CLAP model.
    
    CLAP is trained to align text and audio embeddings, so we can directly
    compute cosine similarity between them.
    """
    # Process text
    text_inputs = clap_processor(
        text=[caption_text],
        return_tensors="pt",
        padding=True,
        truncation=True,
        max_length=77
    ).to(device)
    
    # Process audio
    audio_inputs = clap_processor(
        audios=[audio_arr],
        return_tensors="pt",
        padding=True,
        sampling_rate=48000
    ).to(device)
    
    # Get embeddings
    with torch.no_grad():
        text_features = clap_model.get_text_features(**text_inputs)
        audio_features = clap_model.get_audio_features(**audio_inputs)
    
    # Normalize
    text_features = text_features / text_features.norm(dim=-1, keepdim=True)
    audio_features = audio_features / audio_features.norm(dim=-1, keepdim=True)
    
    # Cosine similarity (higher = better alignment)
    similarity = (text_features @ audio_features.T).item()
    
    return similarity


def extract_clap_audio_embedding(clap_model, clap_processor, device, audio_arr):
    """
    Extract audio embedding using CLAP for L_dyn computation.
    """
    audio_inputs = clap_processor(
        audios=[audio_arr],
        return_tensors="pt",
        padding=True,
        sampling_rate=48000
    ).to(device)
    
    with torch.no_grad():
        audio_features = clap_model.get_audio_features(**audio_inputs)
    
    # Normalize
    audio_features = audio_features / audio_features.norm(dim=-1, keepdim=True)
    
    return audio_features.cpu().numpy()


# ============================================================================
# Metrics Computation
# ============================================================================


def compute_l_dyn(audio_embeddings):
    """
    L_dyn: Dynamic style smoothness across consecutive segments.
    
    Formula: (1/K-1) * Σ ||emb_{i+1} - emb_i||²
    
    Lower = smoother transitions (better consistency)
    """
    if len(audio_embeddings) < 2:
        return 0.0
    
    embeddings = np.array(audio_embeddings)
    
    # Compute consecutive deltas
    deltas = np.diff(embeddings, axis=0)
    
    # L2 norm squared for each transition
    delta_magnitudes = np.linalg.norm(deltas, axis=1) ** 2
    
    # Average
    return float(np.mean(delta_magnitudes))


