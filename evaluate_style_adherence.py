def evaluate_segment(model, tokenizer, description_tokenizer, clap_model, clap_processor, device, segment, style_caption,
                     generated_audio_path):
    """
    Evaluate a single segment: generate audio and compute L_sem.

    Returns:
        dict with l_sem score and metadata
    """
    segment_id = segment['segment_id']
    text = segment['text']

    # Generate audio
    try:
        generate_speech(
            model=model,
            tokenizer=tokenizer,
            description_tokenizer=description_tokenizer,
            device=device,
            text=text,
            style_caption=style_caption,
            output_path=generated_audio_path,
        )
    except Exception as e:
        import traceback
        error_details = traceback.format_exc()
        print(f"Generation error for {segment_id}: {error_details}")
        return {
            'segment_id': segment_id,
            'l_sem': None,
            'error': str(e),
            'style_caption': style_caption,
        }

    # Compute L_sem using CLAP
    try:
        # Load generated audio
        audio_arr, sr = sf.read(generated_audio_path)
        
        # Resample for CLAP
        if sr != 48000:
            audio_arr = librosa.resample(audio_arr, orig_sr=sr, target_sr=48000)
        
        # Compute L_sem using CLAP
        if clap_model is not None:
            l_sem = compute_l_sem_clap(
                clap_model, clap_processor, device, style_caption, audio_arr
            )
        else:
            # Fallback: set to None if CLAP not available
            l_sem = None
    except Exception as e:
        return {
            'segment_id': segment_id,
            'l_sem': None,
            'error': f"L_sem computation failed: {str(e)}",
            'style_caption': style_caption,
        }

    return {
        'segment_id': segment_id,
        'l_sem': l_sem,
        'style_caption': style_caption,
        'character': segment['character'],
        'story': segment['story'],
        'generated_audio': generated_audio_path,
    }


def evaluate_story(model, tokenizer, description_tokenizer, clap_model, clap_processor, device, story_segments, style_captions):
    """
    Evaluate a complete story: compute L_dyn across all segments.

    Returns:
        dict with l_dyn score and per-segment l_sem scores
    """
    story_id = story_segments[0]['story']
    results = {
        'story_id': story_id,
        'segments': [],
        'l_dyn': None,
        'l_sem_avg': None,
        'caption_stats': {
            'total': len(story_segments),
            'gpt4o_generated': 0,
            'fallback_emotion': 0,
            'fallback_template': 0,
            'failed': 0,
        }
    }

    audio_embeddings = []
    l_sem_scores = []

    print(f"\nEvaluating Story {story_id} ({len(story_segments)} segments)...")

    for seg in tqdm(story_segments, desc=f"Story {story_id}", unit="seg"):
        segment_id = seg['segment_id']
        
        # Get caption with fallback logic
        caption_data = style_captions.get(segment_id, {})
        raw_caption = caption_data.get('style_caption', '')
        
        # Track caption source (per segment)
        caption_source = 'unknown'
        if raw_caption and not raw_caption.startswith('[ERROR]') and not raw_caption.startswith('[EXISTING]'):
            results['caption_stats']['gpt4o_generated'] += 1
            caption_source = 'gpt4o'
        elif raw_caption.startswith('[EXISTING]') or seg.get('emotion'):
            results['caption_stats']['fallback_emotion'] += 1
            caption_source = 'emotion_fallback'
        elif raw_caption.startswith('[ERROR]') or not raw_caption:
            results['caption_stats']['failed'] += 1
            caption_source = 'error_or_missing'
        else:
            results['caption_stats']['fallback_template'] += 1
            caption_source = 'template_fallback'
        
        # Get final caption (with fallbacks)
        style_caption = get_style_caption_for_segment(segment_id, style_captions, seg)

        generated_path = os.path.join(
            GENERATED_AUDIO_DIR, f"{segment_id}_gen.wav"
        )

        # Evaluate segment
        seg_result = evaluate_segment(
            model, tokenizer, description_tokenizer, clap_model, clap_processor, device, seg, style_caption, generated_path
        )
        seg_result['caption_source'] = caption_source
        results['segments'].append(seg_result)

        # Collect for aggregation
        if seg_result['l_sem'] is not None:
            l_sem_scores.append(seg_result['l_sem'])

        # Collect audio embedding for L_dyn (using MFCC features)
        if os.path.exists(generated_path):
            try:
                audio_arr, sr = sf.read(generated_path)
                if sr != 48000:
                    audio_arr = librosa.resample(audio_arr, orig_sr=sr, target_sr=48000)
                # Use CLAP audio features for L_dyn
                if clap_model is not None:
                    audio_emb = extract_clap_audio_embedding(clap_model, clap_processor, device, audio_arr)
                    audio_embeddings.append(audio_emb)
            except:
                pass
    
    # Compute L_dyn
    if len(audio_embeddings) >= 2:
        results['l_dyn'] = compute_l_dyn(audio_embeddings)
    
    # Average L_sem
    if l_sem_scores:
        results['l_sem_avg'] = float(np.mean(l_sem_scores))
    
    return results


def run_full_evaluation():
    """Run complete evaluation on all test segments."""

    # Load IndicParler-TTS model
    model, tokenizer, description_tokenizer, device = load_model()
    
    # Load CLAP model for L_sem evaluation
    clap_model, clap_processor = load_clap_model()

    # Load data
    print("\nLoading data...")
    segments = load_test_segments()
    style_captions = load_style_captions()
    stories = group_segments_by_story(segments)

    # Quick test mode
    if QUICK_TEST:
        print(f"\n=== QUICK TEST MODE ===")
        print(f"Testing with Story {QUICK_TEST_STORY}, first {QUICK_TEST_LIMIT} segments")
        stories = {
            QUICK_TEST_STORY: stories[QUICK_TEST_STORY][:QUICK_TEST_LIMIT]
        }

    print(f"Total segments: {sum(len(s) for s in stories.values())}")
    print(f"Stories: {len(stories)}")
    print(f"Style captions available: {len(style_captions)}")

    # Evaluate each story
    all_results = []
    story_summaries = []

    for story_id, story_segs in stories.items():
        result = evaluate_story(model, tokenizer, description_tokenizer, clap_model, clap_processor, device, story_segs, style_captions)
        all_results.append(result)

        story_summaries.append({
            'story_id': story_id,
            'num_segments': len(story_segs),
            'l_dyn': result['l_dyn'],
            'l_sem_avg': result['l_sem_avg'],
            'caption_stats': result['caption_stats'],
        })

    # Save results
    summary_path = os.path.join(OUTPUT_DIR, "evaluation_summary.json")
    with open(summary_path, 'w', encoding='utf-8') as f:
        json.dump({
            'story_summaries': story_summaries,
            'full_results': all_results,
        }, f, indent=2, ensure_ascii=False)

    # Print summary
    print("\n" + "="*70)
    print("EVALUATION SUMMARY")
    print("="*70)

    print(f"\n{'Story':<10} {'Segments':<10} {'L_sem (↑)':<14} {'L_dyn (↓)':<14}")
    print("-"*48)

    for summary in story_summaries:
        l_sem_str = f"{summary['l_sem_avg']:.4f}" if summary['l_sem_avg'] else "N/A"
        l_dyn_str = f"{summary['l_dyn']:.4f}" if summary['l_dyn'] else "N/A"
        print(f"{summary['story_id']:<10} {summary['num_segments']:<10} {l_sem_str:<14} {l_dyn_str:<14}")

    # Overall statistics
    all_l_sem = [s['l_sem_avg'] for s in story_summaries if s['l_sem_avg'] is not None]
    all_l_dyn = [s['l_dyn'] for s in story_summaries if s['l_dyn'] is not None]

    print("\n" + "-"*48)
    print(f"{'OVERALL':<10} {'':<10} {np.mean(all_l_sem):.4f} (avg){'<14'} {np.mean(all_l_dyn):.4f} (avg)")
    print(f"{'':<10} {'':<10} {np.std(all_l_sem):.4f} (std){'<14'} {np.std(all_l_dyn):.4f} (std)")

    # Caption quality summary
    total_gpt4o = sum(s['caption_stats']['gpt4o_generated'] for s in story_summaries)
    total_emotion = sum(s['caption_stats']['fallback_emotion'] for s in story_summaries)
    total_template = sum(s['caption_stats']['fallback_template'] for s in story_summaries)
    total_failed = sum(s['caption_stats']['failed'] for s in story_summaries)
    total_all = total_gpt4o + total_emotion + total_template + total_failed

    print("\n" + "="*70)
    print("CAPTION QUALITY")
    print("="*70)
    print(f"GPT-4o generated:  {total_gpt4o} ({total_gpt4o/total_all*100:.1f}%)")
    print(f"Emotion fallback:  {total_emotion} ({total_emotion/total_all*100:.1f}%)")
    print(f"Template fallback: {total_template} ({total_template/total_all*100:.1f}%)")
    print(f"Failed/missing:    {total_failed} ({total_failed/total_all*100:.1f}%)")
    
    print("\n" + "="*70)
    print(f"Full results saved to: {summary_path}")
    print(f"Generated audio in: {GENERATED_AUDIO_DIR}/")
    print("="*70)
    
    return all_results


