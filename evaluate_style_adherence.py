def load_clap_model(device=CLAP_DEVICE):
    """Load CLAP model for joint text-audio embeddings."""
    try:
        from transformers import ClapModel, ClapProcessor
        
        print("Loading CLAP model for L_sem evaluation...")
        clap_model = ClapModel.from_pretrained("laion/larger_clap_general").to(device)
        clap_processor = ClapProcessor.from_pretrained("laion/larger_clap_general")
        print("CLAP model loaded successfully!")
        return clap_model, clap_processor
    except Exception as e:
        print(f"Warning: Could not load CLAP model: {e}")
        print("L_sem will be computed using fallback method")
        return None, None


def load_model(model_name=MODEL_NAME, device=DEVICE):
    """Load IndicParler-TTS model and tokenizers."""
    print(f"Loading model: {model_name}")
    print(f"Device: {device}")

    model = ParlerTTSForConditionalGeneration.from_pretrained(
        model_name,
        torch_dtype="auto",
        low_cpu_mem_usage=True,
    ).to(device)

    tokenizer = AutoTokenizer.from_pretrained(model_name)
    description_tokenizer = AutoTokenizer.from_pretrained(
        model.config.text_encoder._name_or_path
    )

    print("Model loaded successfully!")
    return model, tokenizer, description_tokenizer, device


